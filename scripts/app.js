// Builds a double-clickable Hub.app: it starts the server if it isn't already
// running, then opens Hub in your browser. Usage: npm run app:install | npm run app:uninstall
import 'dotenv/config';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const appPath = path.join(os.homedir(), 'Applications', 'Hub.app');
const desktopLink = path.join(os.homedir(), 'Desktop', 'Hub.app');
const port = process.env.PORT || 4321;

const cmd = process.argv[2];

if (cmd === 'uninstall') {
  fs.rmSync(desktopLink, { force: true });
  fs.rmSync(appPath, { recursive: true, force: true });
  console.log('Removed Hub.app.');
  process.exit(0);
}

if (cmd !== 'install') {
  console.log('Usage: node scripts/app.js install|uninstall');
  process.exit(1);
}

// Apps opened from Finder don't get your shell's PATH, so bake in this node.
const launcher = `#!/bin/zsh
# Generated by scripts/app.js. Starts Hub if needed, then opens it.
HUB_DIR=${JSON.stringify(root)}
NODE=${JSON.stringify(process.execPath)}
PING="http://127.0.0.1:${port}/"

cd "$HUB_DIR" || exit 1
mkdir -p data

if ! curl -s -o /dev/null --max-time 1 "$PING"; then
  # Rebuild the UI if it's missing or older than the source.
  if [[ ! -f dist/index.html || -n "$(find client -newer dist/index.html -print -quit)" ]]; then
    "$NODE" node_modules/vite/bin/vite.js build >> data/hub.log 2>&1
  fi
  # Script-based apps can launch under Rosetta on Apple silicon; run node natively.
  ARCH=()
  [[ "$(sysctl -n hw.optional.arm64 2>/dev/null)" == 1 ]] && ARCH=(arch -arm64)
  nohup "\${ARCH[@]}" "$NODE" server/index.js >> data/hub.log 2>&1 &
  for i in {1..40}; do
    curl -s -o /dev/null --max-time 1 "$PING" && break
    sleep 0.25
  done
fi

open "http://localhost:${port}"
`;

const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Hub</string>
  <key>CFBundleDisplayName</key><string>Hub</string>
  <key>CFBundleIdentifier</key><string>com.hub.launcher</string>
  <key>CFBundleExecutable</key><string>Hub</string>
  <key>CFBundleIconFile</key><string>Hub</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>LSUIElement</key><true/>
  <key>LSArchitecturePriority</key><array><string>arm64</string><string>x86_64</string></array>
</dict>
</plist>
`;

fs.rmSync(appPath, { recursive: true, force: true });
const macos = path.join(appPath, 'Contents', 'MacOS');
const resources = path.join(appPath, 'Contents', 'Resources');
fs.mkdirSync(macos, { recursive: true });
fs.mkdirSync(resources, { recursive: true });
fs.writeFileSync(path.join(appPath, 'Contents', 'Info.plist'), plist);
fs.writeFileSync(path.join(macos, 'Hub'), launcher, { mode: 0o755 });

// Icon: the favicon (indigo square + check), drawn with AppKit via JXA so the
// corners stay transparent, then packed with iconutil. Best effort; the app
// works with the generic icon too.
const ICON_JXA = `ObjC.import('AppKit');
function run(argv) {
  const S = 1024;
  const rep = $.NSBitmapImageRep.alloc.initWithBitmapDataPlanesPixelsWidePixelsHighBitsPerSampleSamplesPerPixelHasAlphaIsPlanarColorSpaceNameBytesPerRowBitsPerPixel(
    null, S, S, 8, 4, true, false, $.NSDeviceRGBColorSpace, 0, 0);
  $.NSGraphicsContext.saveGraphicsState;
  $.NSGraphicsContext.setCurrentContext($.NSGraphicsContext.graphicsContextWithBitmapImageRep(rep));
  $.NSColor.colorWithSRGBRedGreenBlueAlpha(0x4f / 255, 0x46 / 255, 0xe5 / 255, 1).setFill;
  $.NSBezierPath.bezierPathWithRoundedRectXRadiusYRadius($.NSMakeRect(100, 100, 824, 824), 185, 185).fill;
  const p = $.NSBezierPath.bezierPath;
  p.moveToPoint($.NSMakePoint(330, S - 528));
  p.lineToPoint($.NSMakePoint(474, S - 672));
  p.lineToPoint($.NSMakePoint(778, S - 368));
  p.setLineWidth(96); p.setLineCapStyle(1); p.setLineJoinStyle(1);
  $.NSColor.whiteColor.setStroke; p.stroke;
  $.NSGraphicsContext.restoreGraphicsState;
  rep.representationUsingTypeProperties($.NSBitmapImageFileTypePNG, $({})).writeToFileAtomically(argv[0], true);
}`;

try {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'hub-icon-'));
  const script = path.join(tmp, 'icon.js');
  const png = path.join(tmp, 'icon.png');
  fs.writeFileSync(script, ICON_JXA);
  execSync(`osascript -l JavaScript "${script}" "${png}"`, { stdio: 'ignore' });
  const iconset = path.join(tmp, 'Hub.iconset');
  fs.mkdirSync(iconset);
  for (const size of [16, 32, 128, 256, 512]) {
    execSync(`sips -z ${size} ${size} "${png}" --out "${iconset}/icon_${size}x${size}.png"`, { stdio: 'ignore' });
    execSync(`sips -z ${size * 2} ${size * 2} "${png}" --out "${iconset}/icon_${size}x${size}@2x.png"`, { stdio: 'ignore' });
  }
  execSync(`iconutil -c icns "${iconset}" -o "${path.join(resources, 'Hub.icns')}"`);
  fs.rmSync(tmp, { recursive: true, force: true });
} catch {
  console.warn('Could not generate the icon; Hub.app will use the default one.');
}

fs.rmSync(desktopLink, { force: true });
fs.symlinkSync(appPath, desktopLink);
execSync(`touch "${appPath}"`); // nudge Finder to pick up the icon

console.log(`Created ${appPath} and a shortcut on your Desktop.`);
console.log('Double-click Hub to open it. Drag it to the Dock to keep it there.');
